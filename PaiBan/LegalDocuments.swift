// MARK: - 协议勾选行（登录页 + 注册页）

/// 协议勾选行（1.3.2.017，照考试宝登录页样式）：圆圈勾选框 + 一行字，
/// 两个书名号是蓝色链接，点开看全文。默认未勾选；未勾选时点登录/注册，
/// 调用方在 doLogin/doRegister 里拦住并提示（别静默失败）。
/// 链接用 AttributedString + paiban-legal scheme，在行内拦截打开 sheet，
/// 文字过长时自然换行、勾选框贴顶。
struct AgreementConsentRow: View {
    @Binding var agreed: Bool
    @State private var presentedDoc: LegalDocument?

    var body: some View {
        HStack(alignment: .top, spacing: 8) {
            Button {
                agreed.toggle()
            } label: {
                Image(systemName: agreed ? "checkmark.circle.fill" : "circle")
                    .font(.system(size: 22))
                    .foregroundColor(agreed ? AppStyle.navyAdaptive : .secondary)
            }
            .buttonStyle(.plain)
            .padding(.top, 1)
            .accessibilityLabel(agreed ? "已同意用户协议和隐私政策，点按取消" : "同意用户协议和隐私政策")
            consentText
                .font(.system(size: 13))
                .foregroundColor(.secondary)
                .padding(.top, 3)
        }
        .environment(\.openURL, OpenURLAction { url in
            if url.scheme == "paiban-legal",
               let doc = LegalDocument(rawValue: url.host ?? "") {
                presentedDoc = doc
                return .handled
            }
            return .systemAction
        })
        .sheet(item: $presentedDoc) { doc in
            NavigationStack {
                LegalDocumentView(document: doc)
                    .toolbar {
                        ToolbarItem(placement: .confirmationAction) {
                            Button("完成") { presentedDoc = nil }
                        }
                    }
            }
        }
    }

    /// 「我已阅读并同意《用户使用协议》和《隐私协议》」：两个书名号是链接。
    private var consentText: Text {
        var agreement = AttributedString("《用户使用协议》")
        agreement.link = LegalDocument.userAgreement.url
        agreement.foregroundColor = .blue
        var privacy = AttributedString("《隐私协议》")
        privacy.link = LegalDocument.privacyPolicy.url
        privacy.foregroundColor = .blue
        return Text("我已阅读并同意") + Text(agreement) + Text("和") + Text(privacy)
    }
}
